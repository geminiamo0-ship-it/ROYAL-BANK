CREATE OR REPLACE FUNCTION public.update_study_plan(
    p_plan_id UUID,
    p_start_date DATE,
    p_exam_date DATE,
    p_study_weekdays SMALLINT[],
    p_missed_strategy TEXT,
    p_reduced_load_factor NUMERIC,
    p_periods JSONB DEFAULT '[]'::jsonb,
    p_category_priorities JSONB DEFAULT '[]'::jsonb
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
    v_plan public.study_plans%ROWTYPE;
BEGIN
    SELECT * INTO v_plan FROM public.study_plans WHERE id = p_plan_id;
    IF NOT FOUND OR v_plan.user_id <> auth.uid() OR v_plan.status <> 'active' THEN
        RAISE EXCEPTION 'STUDY_PLAN_NOT_FOUND';
    END IF;
    IF NOT public.can_access_question_bank(v_plan.question_bank_id) THEN
        RAISE EXCEPTION 'Question bank access denied';
    END IF;
    IF p_exam_date <= p_start_date OR p_study_weekdays IS NULL OR cardinality(p_study_weekdays) = 0
       OR NOT (p_study_weekdays <@ ARRAY[0,1,2,3,4,5,6]::SMALLINT[]) THEN
        RAISE EXCEPTION 'STUDY_PLAN_INVALID_SETTINGS';
    END IF;

    UPDATE public.study_plans SET
        start_date = p_start_date,
        exam_date = p_exam_date,
        study_weekdays = ARRAY(SELECT DISTINCT x FROM unnest(p_study_weekdays) x ORDER BY x),
        missed_strategy = p_missed_strategy,
        reduced_load_factor = p_reduced_load_factor,
        updated_at = timezone('utc'::text, now())
    WHERE id = p_plan_id;

    DELETE FROM public.study_plan_periods WHERE plan_id = p_plan_id;
    INSERT INTO public.study_plan_periods (plan_id, start_date, end_date, mode)
    SELECT p_plan_id, (item->>'start_date')::DATE, (item->>'end_date')::DATE, item->>'mode'
    FROM jsonb_array_elements(COALESCE(p_periods, '[]'::jsonb)) item
    WHERE item->>'mode' IN ('pause', 'reduced')
      AND (item->>'start_date')::DATE <= (item->>'end_date')::DATE;

    DELETE FROM public.study_plan_category_priorities WHERE plan_id = p_plan_id;
    INSERT INTO public.study_plan_category_priorities (plan_id, category_name, priority)
    SELECT p_plan_id, item->>'category', (item->>'priority')::INTEGER
    FROM jsonb_array_elements(COALESCE(p_category_priorities, '[]'::jsonb)) item
    WHERE COALESCE(btrim(item->>'category'), '') <> '';

    PERFORM public.schedule_study_plan_pending(
        p_plan_id,
        GREATEST(p_start_date, CURRENT_DATE)
    );
END;
$$;

