CREATE OR REPLACE FUNCTION public.schedule_study_plan_pending(
    p_plan_id UUID,
    p_from_date DATE DEFAULT NULL
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
    v_plan public.study_plans%ROWTYPE;
    v_first_date DATE;
    v_unfinished INTEGER;
    v_eligible INTEGER;
    v_scheduled INTEGER := 0;
BEGIN
    SELECT * INTO v_plan FROM public.study_plans WHERE id = p_plan_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'STUDY_PLAN_NOT_FOUND';
    END IF;

    v_first_date := GREATEST(v_plan.start_date, COALESCE(p_from_date, v_plan.start_date));

    SELECT COUNT(*)::INTEGER INTO v_unfinished
    FROM (
        SELECT DISTINCT qt.topic_id
        FROM public.question_topics qt
        WHERE qt.question_bank_id = v_plan.question_bank_id
          AND NOT EXISTS (
              SELECT 1 FROM public.study_plan_tasks done
              WHERE done.plan_id = v_plan.id
                AND done.topic_id = qt.topic_id
                AND done.status = 'completed'
          )
    ) unfinished;

    IF v_unfinished = 0 THEN
        RETURN 0;
    END IF;

    SELECT COUNT(*)::INTEGER INTO v_eligible
    FROM generate_series(v_first_date, v_plan.exam_date - 1, interval '1 day') d
    WHERE extract(dow FROM d)::SMALLINT = ANY(v_plan.study_weekdays)
      AND NOT EXISTS (
          SELECT 1 FROM public.study_plan_periods spp
          WHERE spp.plan_id = v_plan.id
            AND spp.mode = 'pause'
            AND d::DATE BETWEEN spp.start_date AND spp.end_date
      );

    IF v_eligible = 0 THEN
        RAISE EXCEPTION 'STUDY_PLAN_NO_ELIGIBLE_DAYS';
    END IF;

    WITH unfinished AS (
        SELECT
            ct.id AS topic_id,
            row_number() OVER (
                ORDER BY
                    COALESCE(spp.priority, 100000),
                    COALESCE(ct.category, ''),
                    ct.display_order,
                    ct.name,
                    ct.id
            ) AS rn,
            count(*) OVER () AS total_topics
        FROM public.content_topics ct
        JOIN (
            SELECT DISTINCT topic_id
            FROM public.question_topics
            WHERE question_bank_id = v_plan.question_bank_id
        ) active_topics ON active_topics.topic_id = ct.id
        LEFT JOIN public.study_plan_category_priorities spp
          ON spp.plan_id = v_plan.id
         AND spp.category_name = COALESCE(ct.category, 'General')
        WHERE ct.question_bank_id = v_plan.question_bank_id
          AND NOT EXISTS (
              SELECT 1 FROM public.study_plan_tasks done
              WHERE done.plan_id = v_plan.id
                AND done.topic_id = ct.id
                AND done.status = 'completed'
          )
    ), eligible_days AS (
        SELECT
            d::DATE AS schedule_date,
            CASE
                WHEN EXISTS (
                    SELECT 1 FROM public.study_plan_periods spp
                    WHERE spp.plan_id = v_plan.id
                      AND spp.mode = 'reduced'
                      AND d::DATE BETWEEN spp.start_date AND spp.end_date
                ) THEN v_plan.reduced_load_factor
                ELSE 1::NUMERIC
            END AS weight
        FROM generate_series(v_first_date, v_plan.exam_date - 1, interval '1 day') d
        WHERE extract(dow FROM d)::SMALLINT = ANY(v_plan.study_weekdays)
          AND NOT EXISTS (
              SELECT 1 FROM public.study_plan_periods spp
              WHERE spp.plan_id = v_plan.id
                AND spp.mode = 'pause'
                AND d::DATE BETWEEN spp.start_date AND spp.end_date
          )
    ), weighted_days AS (
        SELECT
            schedule_date,
            weight,
            sum(weight) OVER (ORDER BY schedule_date) AS cumulative_weight,
            sum(weight) OVER () AS total_weight
        FROM eligible_days
    ), assignments AS (
        SELECT
            u.topic_id,
            (
                SELECT wd.schedule_date
                FROM weighted_days wd
                WHERE wd.cumulative_weight >=
                    (((u.rn::NUMERIC - 0.5) / u.total_topics::NUMERIC) * wd.total_weight)
                ORDER BY wd.schedule_date
                LIMIT 1
            ) AS scheduled_date
        FROM unfinished u
    )
    INSERT INTO public.study_plan_tasks (
        plan_id, topic_id, scheduled_date, status, completed_at, updated_at
    )
    SELECT
        v_plan.id,
        a.topic_id,
        a.scheduled_date,
        'pending',
        NULL,
        timezone('utc'::text, now())
    FROM assignments a
    WHERE a.scheduled_date IS NOT NULL
    ON CONFLICT (plan_id, topic_id)
    DO UPDATE SET
        scheduled_date = EXCLUDED.scheduled_date,
        updated_at = timezone('utc'::text, now())
    WHERE public.study_plan_tasks.status = 'pending';

    GET DIAGNOSTICS v_scheduled = ROW_COUNT;
    RETURN v_scheduled;
END;
$$;

