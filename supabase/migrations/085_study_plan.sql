CREATE OR REPLACE FUNCTION public.refresh_content_topic_links(p_bank_id BIGINT DEFAULT NULL)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
    v_topics INTEGER := 0;
    v_questions INTEGER := 0;
    v_articles INTEGER := 0;
BEGIN
    IF p_bank_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.question_banks qb WHERE qb.id = p_bank_id
    ) THEN
        RAISE EXCEPTION 'STUDY_PLAN_BANK_NOT_FOUND';
    END IF;

    WITH candidates AS (
        SELECT
            qbq.question_bank_id,
            btrim(q.topic) AS topic_name,
            NULLIF(btrim(q.category), '') AS category,
            1 AS source_priority,
            0 AS source_order
        FROM public.question_bank_questions qbq
        JOIN public.questions q ON q.id = qbq.question_id
        WHERE q.topic IS NOT NULL
          AND btrim(q.topic) <> ''
          AND (p_bank_id IS NULL OR qbq.question_bank_id = p_bank_id)

        UNION ALL

        SELECT
            qbla.question_bank_id,
            btrim(COALESCE(NULLIF(la.topic, ''), la.name)) AS topic_name,
            NULLIF(btrim(la.category), '') AS category,
            0 AS source_priority,
            qbla.display_order AS source_order
        FROM public.question_bank_library_articles qbla
        JOIN public.library_articles la ON la.id = qbla.article_id
        WHERE btrim(COALESCE(NULLIF(la.topic, ''), la.name)) <> ''
          AND (p_bank_id IS NULL OR qbla.question_bank_id = p_bank_id)
    ), ranked AS (
        SELECT
            question_bank_id,
            topic_name,
            (array_agg(category ORDER BY source_priority, source_order, topic_name)
                FILTER (WHERE category IS NOT NULL))[1] AS category,
            MIN(source_order) AS display_order
        FROM candidates
        GROUP BY question_bank_id, lower(btrim(topic_name)), topic_name
    ), deduped AS (
        SELECT DISTINCT ON (question_bank_id, lower(btrim(topic_name)))
            question_bank_id,
            topic_name,
            category,
            display_order
        FROM ranked
        ORDER BY question_bank_id, lower(btrim(topic_name)), display_order, topic_name
    )
    INSERT INTO public.content_topics (
        question_bank_id, name, category, display_order, updated_at
    )
    SELECT
        question_bank_id,
        topic_name,
        category,
        display_order,
        timezone('utc'::text, now())
    FROM deduped
    ON CONFLICT (question_bank_id, normalized_name)
    DO UPDATE SET
        name = EXCLUDED.name,
        category = COALESCE(EXCLUDED.category, public.content_topics.category),
        display_order = LEAST(public.content_topics.display_order, EXCLUDED.display_order),
        updated_at = timezone('utc'::text, now());

    GET DIAGNOSTICS v_topics = ROW_COUNT;

    DELETE FROM public.question_topics qt
    WHERE p_bank_id IS NULL OR qt.question_bank_id = p_bank_id;

    INSERT INTO public.question_topics (question_bank_id, question_id, topic_id)
    SELECT
        qbq.question_bank_id,
        q.id,
        ct.id
    FROM public.question_bank_questions qbq
    JOIN public.questions q ON q.id = qbq.question_id
    JOIN public.content_topics ct
      ON ct.question_bank_id = qbq.question_bank_id
     AND ct.normalized_name = lower(btrim(q.topic))
    WHERE q.topic IS NOT NULL
      AND btrim(q.topic) <> ''
      AND (p_bank_id IS NULL OR qbq.question_bank_id = p_bank_id)
    ON CONFLICT (question_bank_id, question_id)
    DO UPDATE SET topic_id = EXCLUDED.topic_id;

    GET DIAGNOSTICS v_questions = ROW_COUNT;

    DELETE FROM public.topic_library_articles tla
    WHERE p_bank_id IS NULL OR tla.question_bank_id = p_bank_id;

    WITH linked AS (
        SELECT
            qbla.question_bank_id,
            ct.id AS topic_id,
            la.id AS article_id,
            qbla.display_order,
            row_number() OVER (
                PARTITION BY qbla.question_bank_id, ct.id
                ORDER BY qbla.display_order, la.id
            ) AS topic_rank
        FROM public.question_bank_library_articles qbla
        JOIN public.library_articles la ON la.id = qbla.article_id
        JOIN public.content_topics ct
          ON ct.question_bank_id = qbla.question_bank_id
         AND ct.normalized_name = lower(btrim(COALESCE(NULLIF(la.topic, ''), la.name)))
        WHERE (p_bank_id IS NULL OR qbla.question_bank_id = p_bank_id)
    )
    INSERT INTO public.topic_library_articles (
        question_bank_id, topic_id, article_id, is_primary, display_order
    )
    SELECT
        question_bank_id,
        topic_id,
        article_id,
        topic_rank = 1,
        display_order
    FROM linked
    ON CONFLICT (question_bank_id, topic_id, article_id)
    DO UPDATE SET
        is_primary = EXCLUDED.is_primary,
        display_order = EXCLUDED.display_order;

    GET DIAGNOSTICS v_articles = ROW_COUNT;

    RETURN jsonb_build_object(
        'topics_touched', v_topics,
        'question_links', v_questions,
        'article_links', v_articles
    );
END;
$$;

REVOKE ALL ON FUNCTION public.refresh_content_topic_links(BIGINT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.refresh_content_topic_links(BIGINT) TO service_role;

-- Keep canonical topic links current at the same explicit content-refresh boundary used by imports.
CREATE OR REPLACE FUNCTION public.content_manager_refresh_counts()
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
    v_topic_refresh JSONB;
BEGIN
    PERFORM public.refresh_bank_question_stats();
    REFRESH MATERIALIZED VIEW public.question_bank_topic_counts;
    v_topic_refresh := public.refresh_content_topic_links(NULL);

    RETURN jsonb_build_object(
        'refreshed', TRUE,
        'refreshed_at', clock_timestamp(),
        'canonical_topics', v_topic_refresh
    );
END;
$$;

REVOKE ALL ON FUNCTION public.content_manager_refresh_counts() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.content_manager_refresh_counts() TO service_role;

CREATE TABLE IF NOT EXISTS public.study_plans (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    question_bank_id BIGINT NOT NULL REFERENCES public.question_banks(id) ON DELETE CASCADE,
    start_date DATE NOT NULL,
    exam_date DATE NOT NULL,
    study_weekdays SMALLINT[] NOT NULL DEFAULT ARRAY[1,2,3,4,5]::SMALLINT[],
    missed_strategy TEXT NOT NULL DEFAULT 'redistribute'
        CHECK (missed_strategy IN ('next_free_day', 'redistribute')),
    reduced_load_factor NUMERIC(4,3) NOT NULL DEFAULT 0.5
        CHECK (reduced_load_factor > 0 AND reduced_load_factor <= 1),
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CHECK (exam_date > start_date),
    CHECK (cardinality(study_weekdays) > 0),
    CHECK (study_weekdays <@ ARRAY[0,1,2,3,4,5,6]::SMALLINT[])
);

