-- Canonical topic identity and Study Plan backend.
-- Topic identity is bank + normalized topic name. Category is display/priority metadata,
-- never part of identity, so legacy category spelling variants do not split one topic.

CREATE TABLE IF NOT EXISTS public.content_topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_bank_id BIGINT NOT NULL REFERENCES public.question_banks(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    normalized_name TEXT GENERATED ALWAYS AS (lower(btrim(name))) STORED,
    category TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    UNIQUE (question_bank_id, normalized_name),
    UNIQUE (question_bank_id, id)
);

CREATE INDEX IF NOT EXISTS idx_content_topics_bank_category_order
    ON public.content_topics(question_bank_id, category, display_order, name);

CREATE TABLE IF NOT EXISTS public.question_topics (
    question_bank_id BIGINT NOT NULL REFERENCES public.question_banks(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES public.questions(id) ON DELETE CASCADE,
    topic_id BIGINT NOT NULL REFERENCES public.content_topics(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    PRIMARY KEY (question_bank_id, question_id, topic_id),
    UNIQUE (question_bank_id, question_id)
);

CREATE INDEX IF NOT EXISTS idx_question_topics_topic_question
    ON public.question_topics(topic_id, question_id);

CREATE TABLE IF NOT EXISTS public.topic_library_articles (
    question_bank_id BIGINT NOT NULL REFERENCES public.question_banks(id) ON DELETE CASCADE,
    topic_id BIGINT NOT NULL REFERENCES public.content_topics(id) ON DELETE CASCADE,
    article_id TEXT NOT NULL REFERENCES public.library_articles(id) ON DELETE CASCADE,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    PRIMARY KEY (question_bank_id, topic_id, article_id),
    UNIQUE (question_bank_id, article_id)
);

CREATE INDEX IF NOT EXISTS idx_topic_library_articles_primary
    ON public.topic_library_articles(question_bank_id, topic_id, is_primary DESC, display_order, article_id);

