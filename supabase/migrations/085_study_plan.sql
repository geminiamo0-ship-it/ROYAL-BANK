CREATE OR REPLACE FUNCTION public.get_study_plan_catalog(p_bank_id BIGINT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
    v_result JSONB;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Authentication required';
    END IF;
    IF NOT public.can_access_question_bank(p_bank_id) THEN
        RAISE EXCEPTION 'Question bank access denied';
    END IF;

    SELECT jsonb_build_object(
        'bank_id', p_bank_id,
        'topic_count', COUNT(*),
        'categories', COALESCE(
            jsonb_agg(category_payload ORDER BY category_name),
            '[]'::jsonb
        )
    )
    INTO v_result
    FROM (
        SELECT
            COALESCE(ct.category, 'General') AS category_name,
            jsonb_build_object(
                'name', COALESCE(ct.category, 'General'),
                'topic_count', COUNT(*),
                'topics', jsonb_agg(
                    jsonb_build_object(
                        'id', ct.id,
                        'name', ct.name,
                        'question_count', question_count,
                        'article_id', article_id
                    ) ORDER BY ct.display_order, ct.name
                )
            ) AS category_payload
        FROM public.content_topics ct
        JOIN LATERAL (
            SELECT COUNT(*)::INTEGER AS question_count
            FROM public.question_topics qt
            WHERE qt.question_bank_id = p_bank_id
              AND qt.topic_id = ct.id
        ) qc ON qc.question_count > 0
        LEFT JOIN LATERAL (
            SELECT tla.article_id
            FROM public.topic_library_articles tla
            WHERE tla.question_bank_id = p_bank_id
              AND tla.topic_id = ct.id
            ORDER BY tla.is_primary DESC, tla.display_order, tla.article_id
            LIMIT 1
        ) article ON TRUE
        CROSS JOIN LATERAL (SELECT qc.question_count, article.article_id) values_row
        WHERE ct.question_bank_id = p_bank_id
        GROUP BY COALESCE(ct.category, 'General')
    ) grouped;

    RETURN COALESCE(v_result, jsonb_build_object(
        'bank_id', p_bank_id,
        'topic_count', 0,
        'categories', '[]'::jsonb
    ));
END;
$$;

REVOKE ALL ON FUNCTION public.get_study_plan_catalog(BIGINT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_study_plan_catalog(BIGINT) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.create_study_plan(
    p_bank_id BIGINT,
    p_start_date DATE,
    p_exam_date DATE,
    p_study_weekdays SMALLINT[],
    p_missed_strategy TEXT DEFAULT 'redistribute',
    p_reduced_load_factor NUMERIC DEFAULT 0.5,
    p_periods JSONB DEFAULT '[]'::jsonb,
    p_category_priorities JSONB DEFAULT '[]'::jsonb
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
    v_plan_id UUID;
    v_topics INTEGER;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Authentication required';
    END IF;
    IF NOT public.can_access_question_bank(p_bank_id) THEN
        RAISE EXCEPTION 'Question bank access denied';
    END IF;
    IF p_start_date IS NULL OR p_exam_date IS NULL OR p_exam_date <= p_start_date THEN
        RAISE EXCEPTION 'STUDY_PLAN_INVALID_DATES';
    END IF;
    IF p_study_weekdays IS NULL OR cardinality(p_study_weekdays) = 0
       OR NOT (p_study_weekdays <@ ARRAY[0,1,2,3,4,5,6]::SMALLINT[]) THEN
        RAISE EXCEPTION 'STUDY_PLAN_INVALID_WEEKDAYS';
    END IF;
    IF p_missed_strategy NOT IN ('next_free_day', 'redistribute') THEN
        RAISE EXCEPTION 'STUDY_PLAN_INVALID_MISSED_STRATEGY';
    END IF;
    IF p_reduced_load_factor <= 0 OR p_reduced_load_factor > 1 THEN
        RAISE EXCEPTION 'STUDY_PLAN_INVALID_REDUCED_LOAD';
    END IF;

    SELECT COUNT(DISTINCT qt.topic_id)::INTEGER INTO v_topics
    FROM public.question_topics qt
    WHERE qt.question_bank_id = p_bank_id;
    IF v_topics = 0 THEN
        RAISE EXCEPTION 'STUDY_PLAN_NO_TOPICS';
    END IF;

    UPDATE public.study_plans
    SET status = 'archived', updated_at = timezone('utc'::text, now())
    WHERE user_id = auth.uid()
      AND question_bank_id = p_bank_id
      AND status = 'active';

    INSERT INTO public.study_plans (
        user_id, question_bank_id, start_date, exam_date, study_weekdays,
        missed_strategy, reduced_load_factor
    ) VALUES (
        auth.uid(), p_bank_id, p_start_date, p_exam_date,
        ARRAY(SELECT DISTINCT x FROM unnest(p_study_weekdays) x ORDER BY x),
        p_missed_strategy, p_reduced_load_factor
    ) RETURNING id INTO v_plan_id;

    INSERT INTO public.study_plan_periods (plan_id, start_date, end_date, mode)
    SELECT
        v_plan_id,
        (item->>'start_date')::DATE,
        (item->>'end_date')::DATE,
        item->>'mode'
    FROM jsonb_array_elements(COALESCE(p_periods, '[]'::jsonb)) item
    WHERE item->>'mode' IN ('pause', 'reduced')
      AND (item->>'start_date')::DATE <= (item->>'end_date')::DATE
      AND (item->>'end_date')::DATE >= p_start_date
      AND (item->>'start_date')::DATE < p_exam_date;

    INSERT INTO public.study_plan_category_priorities (plan_id, category_name, priority)
    SELECT
        v_plan_id,
        item->>'category',
        (item->>'priority')::INTEGER
    FROM jsonb_array_elements(COALESCE(p_category_priorities, '[]'::jsonb)) item
    WHERE COALESCE(btrim(item->>'category'), '') <> ''
    ON CONFLICT (plan_id, category_name) DO UPDATE SET priority = EXCLUDED.priority;

    PERFORM public.schedule_study_plan_pending(v_plan_id, p_start_date);
    RETURN v_plan_id;
END;
$$;

